async function withVolumeRetry(phrases, attempts = 4) {
  for (let attempt = 1; ; attempt++) {
    try {
      return await withVolume(phrases, 50)
    } catch (error) {
      if (attempt >= attempts) throw error
      console.warn(`  сбой (${error.message}), повтор ${attempt + 1}/${attempts}`)
      await new Promise(resolve => setTimeout(resolve, 3000 * attempt))
    }
  }
}

/**
 * Отсев без сети: дубли по ключу Директа — в наборе, между наборами и с уже
 * заведёнными фразами кампаний.
 */
export function freshCandidates(junk = JUNK, taken = takenKeys()) {
  const seen = new Set(taken)
  return junk.map(set => {
    const fresh = []
    for (const phrase of set.candidates) {
      const key = phraseKey(phrase)
      if (seen.has(key)) continue
      seen.add(key)
      fresh.push(phrase)
    }
    return { ...set, fresh }
  })
}

/** Ключи всех фраз, уже заведённых в кабинете excel-to-app. */
export function takenKeys() {
  const profiles = ['excel', 'praktikum', 'praktikum-roles', 'adept', 'partner']
  return new Set(profiles.flatMap(name => groupsFor(PROFILES[name]).flatMap(g => g.keywords)).map(phraseKey))
}

async function main() {
  if (!process.env.DIRECT_TOKEN) {
    console.error('DIRECT_TOKEN не задан — охват не проверить')
    process.exit(1)
  }
  for (const set of freshCandidates()) {
    console.log(`${set.profile}: кандидатов ${set.candidates.length}, новых ${set.fresh.length} — проверка охвата`)
    // Цель — охватить всех, поэтому лишнее не обрезается, а уходит в следующую группу.
    const alive = await withVolumeRetry(set.fresh)
    console.log(`  с охватом: ${alive.length}`)
    const groups = []
    for (let i = 0; i < alive.length; i += LIMIT) {
      const n = groups.length + 1
      groups.push({ slug: `junk-${n}`, name: `Мусорные ключи ${n}`, minusWords: [], keywords: alive.slice(i, i + LIMIT) })
    }
    writeFileSync(set.file, JSON.stringify({
      _comment: `Мусорные ключи кампаний ${PROFILES[set.profile].path} (issue #688): абстрактные слова, ${set.theme}. Приём из статьи https://ideav.ru/blog/posts/o-polze-musornyh-klyuchei-v-yandeksdirekte/ — при оплате за конверсии случайный показ бесплатен, платим только за цель. Минус-слов нет. С фразами других кампаний кабинета и с мусором соседних посадочных не пересекаются (без учёта окончаний). Собраны scripts/junk-build-keywords.mjs, охват проверен keywordsresearch.hasSearchVolume ${new Date().toISOString().slice(0, 10)}.`,
      groups,
    }, null, 2) + '\n')
    console.log(`  записано: ${set.file}`)
  }
}


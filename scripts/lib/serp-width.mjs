/** Ширина неизвестного символа: как у «о» — чтобы оценка не занижалась. */
const FALLBACK = 556

/** Лимиты выдачи, в пикселях. */
export const TITLE_LIMIT_PX = 580
export const DESCRIPTION_LIMIT_PX = 1000

/** Размеры шрифта, которыми меряют выдачу. */
const TITLE_FONT_PX = 20
const DESCRIPTION_FONT_PX = 13.33

/** Ширина текста в пикселях при заданном размере Arial. */
export function textWidthPx(text, fontSizePx) {
  let units = 0
  for (const ch of String(text)) units += ARIAL[ch] ?? FALLBACK
  return Math.round((units * fontSizePx) / 1000)
}

export function titleWidthPx(text) {
  return textWidthPx(text, TITLE_FONT_PX)
}

export function descriptionWidthPx(text) {
  return textWidthPx(text, DESCRIPTION_FONT_PX)
}

/**
 * Символы вне обычной русской раскладки: «дѾступа» вместо «доступа» ломает и
 * поиск по странице, и попадание в запрос, а глазом почти не видно (issue #516).
 * Возвращает список найденных чужих букв — пустой, если текст чистый.
 */
export function findLookalikeCyrillic(text) {
  const allowed = new Set('абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ')
  const found = new Set()
  for (const ch of String(text)) {
    const code = ch.codePointAt(0)
    // Кириллица (U+0400–U+04FF) и её расширения (U+0500–U+052F, U+A640–U+A69F).
    const isCyrillicBlock =
      (code >= 0x0400 && code <= 0x052f) || (code >= 0xa640 && code <= 0xa69f)
    if (isCyrillicBlock && !allowed.has(ch)) found.add(ch)
  }
  return [...found]
}

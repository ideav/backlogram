const STOP = new Set(['в', 'во', 'и', 'для', 'с', 'со', 'на', 'по', 'без', 'из', 'к', 'от', 'до', 'за', 'о', 'об', 'у', 'а', 'или', 'как', 'что', 'ли'])

/** Ключ фразы «как видит Директ»: без служебных слов, окончаний и порядка. */
export function phraseKey(phrase) {
  return phrase.toLowerCase().replace(/ё/g, 'е').split(/[\s-]+/)
    .filter(w => w && !STOP.has(w))
    .map(w => w.slice(0, 5))
    .sort()
    .join(' ')
}

async function main() {
  if (!process.env.DIRECT_TOKEN) {
    console.error('DIRECT_TOKEN не задан — охват не проверить')
    process.exit(1)
  }
  const negatives = negativesFor(PROFILES.praktikum)
  const taken = new Set([
    ...groupsFor(PROFILES.praktikum).flatMap(g => g.keywords),
    ...groupsFor(PROFILES.excel).flatMap(g => g.keywords),
  ].map(phraseKey))
  console.log(`занято фразами praktikum-cpa и главной: ${taken.size} ключей`)

  const groups = []
  for (const role of ROLES) {
    const fresh = []
    for (const phrase of role.candidates) {
      const key = phraseKey(phrase)
      if (taken.has(key)) continue
      if (phrase.split(/\s+/).some(w => negatives.includes(w))) continue
      taken.add(key)
      fresh.push(phrase)
    }
    console.log(`${role.slug}: кандидатов ${role.candidates.length}, новых ${fresh.length} — проверка охвата`)
    const alive = (await withVolumeRetry(fresh)).slice(0, LIMIT)
    console.log(`  с охватом: ${alive.length}`)
    groups.push({ slug: role.slug, name: role.name, keywords: alive, minusWords: [] })
  }

  writeFileSync(OUT, JSON.stringify({
    _comment: 'Фразы кампаний-гипотез практикума по ролям (issue #670). У каждой роли свои запросы под её посыл; с praktikum-cpa (#668), главной и другими ролями не пересекаются (без учёта предлогов, окончаний и порядка слов). Собраны scripts/praktikum-roles-build-keywords.mjs, охват проверен keywordsresearch.hasSearchVolume 07.10.2026.',
    groups,
  }, null, 2) + '\n')
  console.log(`записано: ${OUT}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => {
    console.error('\n' + error.message)
    process.exit(1)
  })
}

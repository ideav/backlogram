/** Директ через туннель иногда рвёт соединение — запрос повторяется. */
async function withVolumeRetry(phrases, attempts = 4) {
  for (let attempt = 1; ; attempt++) {
    try {
      return await withVolume(phrases, 50)
    } catch (error) {
      if (attempt >= attempts) throw error
      console.warn(`  сбой (${error.message}), повтор ${attempt + 1}/${attempts}`)
      await new Promise(resolve => setTimeout(resolve, 3000 * attempt))
    }
  }
}


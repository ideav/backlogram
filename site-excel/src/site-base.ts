// Путь сайта на хосте. Подставляется сборкой из SITE_BASE — и Vite, и
// пререндером статических страниц (scripts/prerender-site-excel.mjs).
//
// До issue #626 весь сайт был одной страницей в корне, и картинки ссылались
// относительным `img/…`. Со страницами `/keysy/<slug>/` так больше нельзя:
// относительный путь оттуда указывает внутрь каталога кейса. Поэтому все
// внутренние адреса собираются от этого значения.
declare const __SITE_BASE__: string

export const SITE_BASE: string =
  typeof __SITE_BASE__ === 'string' && __SITE_BASE__ !== '' ? __SITE_BASE__ : '/'

// Русская микротипографика: неразрывные пробелы.
//
// Зачем: SEO-аудит 02.10.2026 (issue #627, п. 13) посчитал в сыром HTML сотни
// мест, где короткий предлог или союз остаётся в конце строки, а тире
// переносится на новую. Issue #753 добавил вторую половину правила: число не
// отрывается от единицы измерения и от счётного слова — «в 4 раза» рвалось на
// «в 4» и «раза» прямо в hero живой страницы.
//
// Модуль — plain ESM с типами в typography.d.ts, чтобы его могли импортировать
// и Vite-сборка (React), и Node-скрипты сборки: применяется он в двух местах —
// scripts/apply-typography.mjs ко всем страницам dist/ после пререндеров и
// src/lib/install-typography.ts к уже смонтированному SPA (React
// перерисовывает статический снапшот из исходных строк, и расставленные в
// HTML &nbsp; после монтирования уходят вместе с ним).
//
// Правила сознательно узкие: правим только то, что ломается почти всегда, и ни
// при каких условиях не трогаем содержимое тегов и атрибутов.

// Неразрывный пробел в двух представлениях: сущность для HTML-строк и символ
// U+00A0 для живых текстовых узлов DOM — узлу нельзя присвоить «&nbsp;» как
// текст, он им и останется на экране.
const NBSP_ENTITY = '&nbsp;'
const NBSP_CHAR = '\u00A0'

// Односимвольные слова, двух- и частые трёхбуквенные предлоги и союзы,
// которые нельзя оставлять в конце строки. Список закрытый: расширять его
// наугад опасно — склеенный блок «не» + длинное слово хуже, чем висящий
// предлог.
const SHORT_WORDS = [
  'а', 'в', 'и', 'к', 'о', 'с', 'у', 'я',
  'во', 'до', 'за', 'из', 'ко', 'на', 'не', 'ни', 'но', 'об', 'от', 'по', 'со',
  'без', 'для', 'над', 'под', 'при', 'про', 'как', 'или',
]

// Числительные словами перед счётным словом: «за пару минут», «на десять
// страниц». Тоже закрытый список — числительных конечное число; наречия
// количества («много», «несколько») не склеиваем: это не число.
const NUMERALS = [
  'один', 'одна', 'одно', 'два', 'две', 'три', 'четыре', 'пять', 'шесть',
  'семь', 'восемь', 'девять', 'десять', 'одиннадцать', 'двенадцать',
  'тринадцать', 'четырнадцать', 'пятнадцать', 'шестнадцать', 'семнадцать',
  'восемнадцать', 'девятнадцать', 'двадцать', 'тридцать', 'сорок',
  'пятьдесят', 'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто', 'сто',
  'двести', 'триста', 'четыреста', 'пятьсот', 'тысяча', 'тысячу', 'миллион',
  'миллиард', 'полтора', 'полторы', 'пара', 'пару',
]

// Единицы измерения-сокращения: «25 МБ», «120 пар/мин», «5 000 ₽». Список
// закрытый, потому что сокращение легко опознать; полные счётные слова
// («раза», «минуты», «страниц») перечислить нельзя — их держит общее правило
// NUMBER_TAIL_RE.
const UNITS = [
  'МБ', 'КБ', 'ГБ', 'ТБ', '₽', 'руб', 'руб\\.', '%', 'мин', 'сек', 'ч', 'мс',
  'тыс', 'тыс\\.', 'млн', 'млрд', 'шт', 'шт\\.', 'г', 'г\\.', 'кг', 'м', 'км',
]
const NUMBER_UNIT_RE = new RegExp(String.raw`(\d)[ \t]+(${UNITS.join('|')})(?![\wА-Яа-яЁё])`, 'g')

// Цифра + следующий за пробелом символ: слово или другая цифра. Общее правило
// вместо списка счётных слов: «4 раза», «2 минуты», «10 страниц», разряды
// одного числа («75 000»), «2026 году» — всё это переносить не нужно, а
// оверглю ограничен длиной одного слова.
const NUMBER_TAIL_RE = /(\d)[ \t]+(?=[\dA-Za-zА-Яа-яЁё])/g

// Слева от короткого слова — начало текста, пробел, скобка, кавычка, тире или
// уже поставленный неразрывный пробел (символ U+00A0 и так входит в \s,
// отдельно упомянута только сущность). Разделитель смотрим lookbehind'ом,
// а не группой: иначе в «и в базе» обработается только первое слово — его
// совпадение съест пробел, который нужен второму как разделитель.
const SHORT_WORD_RE = new RegExp(
  String.raw`(?<=^|[\s(\[«"'—–]|&nbsp;)(${SHORT_WORDS.join('|')})\s+`,
  'gi',
)
const NUMERAL_RE = new RegExp(
  String.raw`(?<=^|[\s(\[«"'—–]|&nbsp;)(${NUMERALS.join('|')})\s+`,
  'gi',
)

/**
 * Собирает функцию склейки для одного представления неразрывного пробела:
 * nbsp() склеивает сущностью (HTML-строки), nbspText() — символом U+00A0
 * (живые текстовые узлы DOM).
 */
function makeNbsp(nbsp) {
  return (text) =>
    text
      .replace(SHORT_WORD_RE, (_, word) => `${word}${nbsp}`)
      .replace(NUMERAL_RE, (_, word) => `${word}${nbsp}`)
      .replace(NUMBER_UNIT_RE, (_, digit, unit) => `${digit}${nbsp}${unit}`)
      .replace(NUMBER_TAIL_RE, (_, digit) => `${digit}${nbsp}`)
      // тире не должно начинать строку
      .replace(/\s+([—–])/g, `${nbsp}$1`)
}

/**
 * Склеивает неразрывными пробелами один фрагмент обычного текста.
 * На вход ждёт уже экранированный HTML-текст (без тегов).
 */
export const nbsp = makeNbsp(NBSP_ENTITY)

/** То же, но для текста вне HTML: склейка символом U+00A0, без сущностей. */
export const nbspText = makeNbsp(NBSP_CHAR)

// Элементы с «сырым» содержимым: внутри них разметки нет, зато есть символ «<»
// (`for (var j = 0; j < n; j++)` в счётчике Метрики). Поэтому их проходим не
// общим сканером, а прыжком до закрывающего тега — как это делает настоящий
// HTML-парсер для raw text elements.
const RAW_TEXT_TAGS = /^(script|style|textarea)$/i

// Элементы с нормальной разметкой внутри, но без текста для типографики.
const SKIP_TAGS = /^(template|pre|code|svg)$/i

/**
 * Применяет nbsp() только к текстовым узлам HTML: сами теги, атрибуты,
 * комментарии и содержимое SKIP_TAGS остаются байт-в-байт как были.
 */
export function nbspHtml(html) {
  let out = ''
  let i = 0
  let skipDepth = 0

  while (i < html.length) {
    const lt = html.indexOf('<', i)
    if (lt === -1) {
      out += skipDepth > 0 ? html.slice(i) : nbsp(html.slice(i))
      break
    }

    const text = html.slice(i, lt)
    out += skipDepth > 0 ? text : nbsp(text)

    // Комментарии и CDATA пропускаем целиком: внутри них может быть «>».
    if (html.startsWith('<!--', lt)) {
      const end = html.indexOf('-->', lt)
      if (end === -1) {
        out += html.slice(lt)
        break
      }
      out += html.slice(lt, end + 3)
      i = end + 3
      continue
    }

    const gt = html.indexOf('>', lt)
    if (gt === -1) {
      out += html.slice(lt)
      break
    }

    const tag = html.slice(lt, gt + 1)
    out += tag
    i = gt + 1

    const m = /^<(\/?)([a-zA-Z][a-zA-Z0-9-]*)/.exec(tag)
    if (!m || tag.endsWith('/>')) continue

    const [, closing, name] = m

    if (!closing && RAW_TEXT_TAGS.test(name)) {
      // всё до закрывающего тега — как есть, ничего не разбирая
      const close = html.toLowerCase().indexOf(`</${name.toLowerCase()}`, i)
      if (close === -1) {
        out += html.slice(i)
        i = html.length
      } else {
        out += html.slice(i, close)
        i = close
      }
      continue
    }

    if (SKIP_TAGS.test(name)) {
      if (closing) skipDepth = Math.max(0, skipDepth - 1)
      else skipDepth += 1
    }
  }

  return out
}

/**
 * Оценка по ответам — локальная логика из заготовки victor (issue #745):
 * считаем условные «сущности» и «формы» по типу системы, функциям и масштабу
 * команды, затем относим проект к одной из пяти категорий. Пороги совпадают с
 * заготовкой; тесты (tests/issue-745-quiz.test.mjs) держат их на месте.
 */
export function analyzeEstimate({ systemType = '', userCount = '', features = [] }) {
  let entities = 0
  let forms = 0
  const found = []

  if (systemType.includes('CRM')) {
    entities += 4 // Клиент, Контакт, Сделка, Задача
    forms += 2
    found.push('База клиентов и контактов', 'Воронка сделок со стадиями')
  } else if (systemType.includes('Склад')) {
    entities += 5 // Товар, Заказ, Поставщик, Склад, Документ
    forms += 3
    found.push('Учёт товаров и остатков', 'Заказы и поставки')
  } else if (systemType.includes('Проект')) {
    entities += 4 // Проект, Задача, Сотрудник, Комментарий
    forms += 2
    found.push('Проекты и задачи', 'Прогресс и дедлайны')
  } else if (systemType.includes('Портал')) {
    entities += 4 // Сотрудник, Документ, Новость, Заявка
    forms += 2
    found.push('Портал для сотрудников', 'Документы и заявки')
  } else {
    entities += 3
    forms += 1
    found.push('Система под ваши процессы')
  }

  for (const f of features) {
    if (f.includes('кабинет')) {
      entities += 1
      forms += 1
      found.push('Вход по логину/паролю с личными кабинетами')
    }
    if (f.includes('Таблицы')) {
      entities += 1
      found.push('Таблицы с поиском, сортировкой и фильтрами')
    }
    if (f.includes('загружать')) {
      entities += 1
      forms += 1
      found.push('Загрузка и хранение файлов')
    }
    if (f.includes('Дашборд')) {
      entities += 1
      forms += 1
      found.push('Дашборд с графиками и отчётами')
    }
    if (f.includes('Интеграция')) {
      entities += 2
      found.push('Интеграция с внешними сервисами')
    }
    if (f.includes('уведомления')) {
      entities += 1
      found.push('Автоматические уведомления')
    }
  }

  if (userCount === '50+') {
    entities += 2
    forms += 1
  } else if (userCount === '11-50') {
    entities += 1
  }

  let category, cost, timeline
  if (entities <= 5 && forms <= 2) {
    category = 'Базовый'
    cost = 'от 75 000 ₽'
    timeline = '2–3 недели'
  } else if (entities <= 10 && forms <= 3) {
    category = 'Стандарт'
    cost = '120 000 – 200 000 ₽'
    timeline = '4–6 недель'
  } else if (entities <= 20 && forms <= 6) {
    category = 'Расширенный'
    cost = '300 000 – 400 000 ₽'
    timeline = '6–10 недель'
  } else if (entities <= 50 && forms <= 10) {
    category = 'Комплексный'
    cost = '450 000 – 600 000 ₽'
    timeline = '10–16 недель'
  } else {
    category = 'Индивидуальный'
    cost = 'обсудим на созвоне'
    timeline = 'по результатам разговора'
  }

  // Вилку функций в результате не раздуваем: пять пунктов сверху достаточно.
  return { category, cost, timeline, features: found.slice(0, 5) }
}

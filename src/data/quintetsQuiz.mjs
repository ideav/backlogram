/** Индекс вопроса по его id (перекос описан именами, а не номерами). */
export function questionIndex(id) {
  return QUESTIONS.findIndex((q) => q.id === id)
}

/** Сработавшие правила перекоса при данном наборе ответов. */
export function crossHits(answers) {
  return CROSS.filter((c) =>
    Object.entries(c.when).every(([id, oi]) => answers[questionIndex(id)] === oi),
  )
}

/**
 * Снимается ли с комбинации штраф: один из чистых вариантов вопрос не тянет
 * (набрал не больше трети веса) — тогда комбинация и есть ответ.
 */
export function rescue(k, r, w) {
  return Math.min(k, r) * 3 <= w
}

/** Балл комбинации: полный балл сильного варианта либо он же минус треть веса. */
export function combo(k, r, w) {
  return rescue(k, r, w) ? Math.max(k, r) : Math.max(0, Math.max(k, r) - Math.round(w / 3))
}

/** Баллы ответа тройкой [Квинтеты, РСУБД, Комбинация]. */
export function points(option, w) {
  return [option[1][0], option[1][1], combo(option[1][0], option[1][1], w)]
}

/** Часы комбинации по вопросу: более подходящее из двух хранилищ. */
export function hoursCombo(pair) {
  const known = pair.filter((v) => v != null)
  return known.length ? Math.min(...known) : null
}

/** Часы ответа тройкой [Квинтеты, РСУБД, Комбинация]. */
export function hours(option) {
  return [option[2][0], option[2][1], hoursCombo(option[2])]
}

/** Потолок шкалы каждого варианта: сумма лучших баллов по всем вопросам. */
export function ceilings() {
  return [0, 1, 2].map((i) =>
    QUESTIONS.reduce((a, q) => a + Math.max(...q.o.map((o) => points(o, q.w)[i])), 0),
  )
}

/** Самый трудоёмкий набор ответов — верхняя граница часов у каждого варианта. */
export function worstHours() {
  return [0, 1, 2].map(
    (i) =>
      QUESTIONS.reduce((a, q) => a + Math.max(...q.o.map((o) => hours(o)[i] || 0)), 0) +
      (i === 2 ? COMBO_SURCHARGE : 0),
  )
}

/**
 * Полный счёт по набору ответов (`answers[i]` — номер выбранного варианта либо
 * null). Возвращает суммы, часы, блокеры, потери баллов и статьи расхода.
 */
export function score(answers) {
  const sum = [0, 0, 0]
  const hrs = [0, 0, 0]
  const blocked = [[], [], []]
  const lost = [[], [], []]
  const spend = [[], [], []]
  let answered = 0

  QUESTIONS.forEach((q, qi) => {
    const oi = answers[qi]
    if (oi == null) return
    answered++
    const option = q.o[oi]
    points(option, q.w).forEach((p, i) => {
      sum[i] += p
      if (p === 0) blocked[i].push(qi + 1)
      else if (p < q.w) lost[i].push({ q: qi + 1, d: q.w - p, note: option[3] })
    })
    hours(option).forEach((v, i) => {
      if (v == null) {
        if (!blocked[i].includes(qi + 1)) blocked[i].push(qi + 1)
        return
      }
      hrs[i] += v
      if (v > 0) spend[i].push({ q: qi + 1, v, note: option[3] })
    })
  })

  const complete = answered === QUESTIONS.length
  if (complete) hrs[2] += COMBO_SURCHARGE
  const cross = crossHits(answers)
  cross.forEach((c) => c.add.forEach((v, i) => (hrs[i] += v)))

  return { sum, hours: hrs, blocked, lost, spend, answered, complete, cross }
}

/** Вариант-победитель и его соперник по трудозатратам — общий вывод для обоих представлений. */
export function verdict(answers) {
  const s = score(answers)
  if (!s.complete) return { ...s, best: null, tie: [], cheapest: null }
  const ok = [0, 1, 2]
    .filter((i) => !s.blocked[i].length)
    .sort((a, b) => s.sum[b] - s.sum[a] || (a === 2 ? 1 : 0) - (b === 2 ? 1 : 0))
  if (!ok.length) return { ...s, best: null, tie: [], cheapest: null }
  const best = ok[0]
  const tie = ok.filter((i) => s.sum[i] === s.sum[best])
  const cheapest = ok.slice().sort((a, b) => s.hours[a] - s.hours[b])[0]
  return { ...s, best, tie, cheapest }
}

/** «12 баллов», «1 балл», «14 баллов» — согласование числительного. */
export function ballWord(n) {
  const m = n % 100
  const k = n % 10
  if (m > 10 && m < 20) return 'баллов'
  if (k === 1) return 'балл'
  if (k >= 2 && k <= 4) return 'балла'
  return 'баллов'
}

/** Часы в подпись: null = «так не делается». */
export function hoursLabel(v) {
  if (v == null) return '—'
  return v === 0 ? '0' : `${v} ч`
}

export function siteSectionBySlug(slug) {
  return SITE_SECTIONS.find((s) => s.slug === slug)
}

/** Все ссылки раздела на страницы сайта — для проверки, что они существуют. */
export function sectionLinks(section) {
  const out = []
  for (const b of section.blocks) {
    for (const it of b.items ?? []) if (it.href) out.push(it)
    for (const l of b.links ?? []) out.push(l)
    for (const c of b.cases ?? []) out.push({ href: c.href })
    if (b.more) out.push(b.more)
  }
  return out
}
